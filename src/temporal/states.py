"""Temporal States and Event records for unattended object reasoning."""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum
from typing import Optional


class AbandonmentState(str, Enum):
    """Enumeration of possible temporal states for an object."""

    UNKNOWN = "UNKNOWN"
    ATTENDED = "ATTENDED"
    OWNER_MOVING_AWAY = "OWNER_MOVING_AWAY"
    SEPARATED = "SEPARATED"
    STATIONARY = "STATIONARY"
    SUSPECTED_ABANDONED = "SUSPECTED_ABANDONED"
    ABANDONED = "ABANDONED"
    RECOVERED = "RECOVERED"


@dataclass
class StateTransitionEvent:
    """Record of a state transition."""

    timestamp: float
    bag_id: int
    owner_id: Optional[int]
    previous_state: AbandonmentState
    new_state: AbandonmentState
    distance: float
    reason: str


@dataclass
class AbandonmentAlert:
    """Record of an alert generated by the system."""

    timestamp: float
    bag_id: int
    owner_id: Optional[int]
    state: AbandonmentState
    separation_duration: float
    distance: float
    bag_bbox: list
    message: str
